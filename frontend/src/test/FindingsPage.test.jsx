import React from 'react';
import { describe, it, expect, vi, beforeEach } from 'vitest';
import { render, screen, act, waitFor, fireEvent } from '@testing-library/react';
import { MemoryRouter, Routes, Route, useNavigate } from 'react-router-dom';
import FindingsPage from '../pages/FindingsPage';
import { datasetService } from '../services/datasetService';
import { researchService } from '../services/researchService';
import { analysisService } from '../services/analysisService';

vi.mock('../services/datasetService', () => ({
  datasetService: {
    listDatasets: vi.fn(),
    getDataset: vi.fn(),
  },
}));

vi.mock('../services/researchService', () => ({
  researchService: {
    getDatasetFindings: vi.fn(),
  },
}));

vi.mock('../services/analysisService', () => ({
  analysisService: {
    getEvidenceGraph: vi.fn(),
  },
}));

// The findings page only needs selectDataset from the workflow context.
const { selectDatasetMock } = vi.hoisted(() => ({ selectDatasetMock: vi.fn() }));

vi.mock('../context/WorkflowContext', async (importOriginal) => {
  const actual = await importOriginal();
  return {
    ...actual,
    useWorkflow: () => ({ datasetId: null, selectDataset: selectDatasetMock }),
  };
});

vi.mock('../components/WorkflowNavigator', () => ({
  default: ({ children }) => <div data-testid="workflow-navigator">{children}</div>,
}));

vi.mock('../components/EvidenceGraphPanel', () => ({
  default: () => null,
  ReliabilityScorecard: () => null,
}));

const apiError = (message) => {
  const err = new Error(message);
  err.response = { data: { message } };
  return err;
};

const datasetDto = (id, name) => ({ id, name, rowCount: 120, columnCount: 6 });

// Shape produced by EvidenceEngine.createFinding for a hypothesis test run.
const hypothesisTestFinding = (id, title) => ({
  id,
  title,
  summary: `Summary of ${title}`,
  evidenceText: 'test=PEARSON, p=0.0031, n=120',
  confidenceLevel: 'HIGH',
  causalityDisclaimer: 'Observational only.',
  evidenceNodes: [{ id: id * 10, nodeType: 'TEST', description: 'stat test node' }],
  createdAt: '2026-03-01T12:00:00Z',
});

let navRef = { current: null };

const NavCapture = () => {
  navRef.current = useNavigate();
  return null;
};

const renderFindingsPage = (initialPath = '/datasets/1/findings') =>
  render(
    <MemoryRouter initialEntries={[initialPath]}>
      <NavCapture />
      <Routes>
        <Route path="/datasets/:id/findings" element={<FindingsPage />} />
        <Route path="/findings" element={<FindingsPage />} />
      </Routes>
    </MemoryRouter>
  );

beforeEach(() => {
  vi.clearAllMocks();
  navRef = { current: null };
  datasetService.listDatasets.mockResolvedValue({
    success: true,
    data: [datasetDto(1, 'Alpha'), datasetDto(2, 'Beta')],
  });
  datasetService.getDataset.mockImplementation(async (id) => ({
    success: true,
    data: datasetDto(Number(id), Number(id) === 1 ? 'Alpha' : 'Beta'),
  }));
  researchService.getDatasetFindings.mockResolvedValue({ success: true, data: [] });
  analysisService.getEvidenceGraph.mockResolvedValue({ success: true, data: null });
});

describe('FindingsPage (FIND-01)', () => {
  it('shows a finding generated by hypothesis testing on the findings page', async () => {
    const finding = hypothesisTestFinding(11, 'Age drives salary (Pearson)');
    researchService.getDatasetFindings.mockResolvedValue({ success: true, data: [finding] });

    renderFindingsPage('/datasets/1/findings');

    expect(await screen.findByText('Age drives salary (Pearson)')).toBeInTheDocument();
    expect(researchService.getDatasetFindings).toHaveBeenCalledWith('1');
    // Evidence of the statistical test is surfaced, proving the finding came
    // from the hypothesis-testing pipeline.
    expect(screen.getByText(/p=0\.0031/)).toBeInTheDocument();
  });

  it('switching between two datasets displays the correct findings for each', async () => {
    researchService.getDatasetFindings.mockImplementation(async (id) =>
      id === '1'
        ? { success: true, data: [hypothesisTestFinding(1, 'Alpha finding')] }
        : { success: true, data: [hypothesisTestFinding(2, 'Beta finding')] }
    );

    renderFindingsPage('/datasets/1/findings');
    expect(await screen.findByText('Alpha finding')).toBeInTheDocument();

    act(() => navRef.current('/datasets/2/findings'));

    expect(await screen.findByText('Beta finding')).toBeInTheDocument();
    expect(screen.queryByText('Alpha finding')).not.toBeInTheDocument();
    expect(researchService.getDatasetFindings).toHaveBeenNthCalledWith(1, '1');
    expect(researchService.getDatasetFindings).toHaveBeenNthCalledWith(2, '2');
  });

  it('discards a slow stale response when the user has already switched datasets', async () => {
    let resolveSlow;
    researchService.getDatasetFindings.mockImplementation((id) => {
      if (id === '1') {
        return new Promise((resolve) => {
          resolveSlow = resolve;
        });
      }
      return Promise.resolve({ success: true, data: [hypothesisTestFinding(2, 'Beta finding')] });
    });

    renderFindingsPage('/datasets/1/findings');

    // Switch away while dataset 1's findings request is still in flight.
    act(() => navRef.current('/datasets/2/findings'));
    expect(await screen.findByText('Beta finding')).toBeInTheDocument();

    // The stale dataset 1 response arrives last — it must not overwrite state.
    act(() => resolveSlow({ success: true, data: [hypothesisTestFinding(1, 'Stale alpha finding')] }));

    expect(screen.getByText('Beta finding')).toBeInTheDocument();
    expect(screen.queryByText('Stale alpha finding')).not.toBeInTheDocument();
  });

  it('works with direct navigation and a page refresh (fresh mount at the route URL)', async () => {
    researchService.getDatasetFindings.mockResolvedValue({
      success: true,
      data: [hypothesisTestFinding(2, 'Beta finding')],
    });

    renderFindingsPage('/datasets/2/findings');

    expect(await screen.findByText('Beta finding')).toBeInTheDocument();
    expect(researchService.getDatasetFindings).toHaveBeenCalledWith('2');
    expect(researchService.getDatasetFindings).not.toHaveBeenCalledWith('1');
  });

  it('shows the empty state when the dataset truly has no findings', async () => {
    researchService.getDatasetFindings.mockResolvedValue({ success: true, data: [] });

    renderFindingsPage('/datasets/1/findings');

    expect(
      await screen.findByText('No Evidence-Backed Findings Generated Yet')
    ).toBeInTheDocument();
    const cta = screen.getByRole('link', { name: /formulate research question/i });
    expect(cta).toHaveAttribute('href', '/datasets/1/research');
  });

  it('shows an API error with retry instead of a false empty state, then recovers', async () => {
    researchService.getDatasetFindings
      .mockRejectedValueOnce(apiError('Findings service unavailable'))
      .mockResolvedValueOnce({
        success: true,
        data: [hypothesisTestFinding(1, 'Recovered finding')],
      });

    renderFindingsPage('/datasets/1/findings');

    expect(await screen.findByText('Findings service unavailable')).toBeInTheDocument();
    // A failed request must NOT be presented as "no findings exist".
    expect(
      screen.queryByText('No Evidence-Backed Findings Generated Yet')
    ).not.toBeInTheDocument();

    fireEvent.click(screen.getByRole('button', { name: /retry/i }));

    expect(await screen.findByText('Recovered finding')).toBeInTheDocument();
    expect(screen.queryByText('Findings service unavailable')).not.toBeInTheDocument();
  });

  it('normalizes the legacy /findings route to the first dataset canonical URL', async () => {
    renderFindingsPage('/findings');

    await waitFor(() => {
      expect(researchService.getDatasetFindings).toHaveBeenCalledWith('1');
    });
  });
});
