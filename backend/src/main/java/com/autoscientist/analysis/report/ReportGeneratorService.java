package com.autoscientist.analysis.report;

import com.autoscientist.entity.*;
import com.autoscientist.util.ColumnSelection;
import com.fasterxml.jackson.core.type.TypeReference;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.springframework.stereotype.Component;

import java.time.format.DateTimeFormatter;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Map;
import java.util.Set;

@Component
public class ReportGeneratorService {

    private static final DateTimeFormatter DATE_FMT = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss");

    private final ObjectMapper objectMapper = new ObjectMapper();

    public String generateScientificReportMarkdown(
            Dataset dataset,
            DataQualityReport qualityReport,
            List<Association> associations,
            ResearchQuestion question,
            List<Hypothesis> hypotheses,
            List<StatisticalTest> statisticalTests,
            List<ModelRun> modelRuns,
            List<Finding> findings) {
        return generateScientificReportMarkdown(dataset, qualityReport, associations, question,
                hypotheses, statisticalTests, modelRuns, findings, null);
    }

    public String generateScientificReportMarkdown(
            Dataset dataset,
            DataQualityReport qualityReport,
            List<Association> associations,
            ResearchQuestion question,
            List<Hypothesis> hypotheses,
            List<StatisticalTest> statisticalTests,
            List<ModelRun> modelRuns,
            List<Finding> findings,
            String driftReportJson) {

        StringBuilder sb = new StringBuilder();
        ModelRun bestRun = modelRuns == null ? null : modelRuns.stream()
                .filter(r -> Boolean.TRUE.equals(r.getIsBestModel())).findFirst()
                .orElse(modelRuns.isEmpty() ? null : modelRuns.get(0));

        String title = question != null
                ? "Scientific Discovery Report: " + question.getQuestionText()
                : "Comprehensive Empirical Discovery Report: " + dataset.getName();

        sb.append("# ").append(title).append("\n\n");
        sb.append("**Generated by AutoScientist AI Autonomous Discovery System**  \n");
        sb.append("**Platform**: AutoScientist AI | *From Raw Data to Evidence-Based Scientific Discovery*  \n");
        sb.append("**Dataset**: `").append(dataset.getName()).append("` (File: `").append(dataset.getOriginalFilename()).append("`)  \n");
        sb.append("**Dataset version**: `v").append(dataset.getVersion() == null ? 1 : dataset.getVersion())
                .append("` | **Source format**: `").append(dataset.getSourceFormat() == null ? "CSV" : dataset.getSourceFormat())
                .append("`").append(dataset.getSheetName() != null ? " | **Worksheet**: `" + dataset.getSheetName() + "`" : "")
                .append("  \n");
        sb.append("**Analysis Timestamp**: `").append(java.time.LocalDateTime.now().format(DATE_FMT)).append("`  \n\n");
        sb.append("---\n\n");

        // Executive summary
        sb.append("## 1. Executive Summary & Abstract\n\n");
        sb.append("This scientific report presents an autonomous, end-to-end empirical investigation of dataset `")
                .append(dataset.getName()).append("`. ");
        sb.append("The dataset comprises **").append(dataset.getRowCount()).append("** observations and **")
                .append(dataset.getColumnCount()).append("** variables, characterized by the system as suitable for **")
                .append(dataset.getDatasetType()).append("** workflows.\n\n");
        if (qualityReport != null) {
            sb.append("Data integrity was evaluated at an overall score of **").append(String.format("%.1f", qualityReport.getOverallScore()))
                    .append(" / 100**, identifying ").append(qualityReport.getTotalIssues()).append(" structural issues requiring attention. ");
        }
        if (findings != null && !findings.isEmpty()) {
            long supported = findings.stream().filter(f -> !"INSUFFICIENT".equals(f.getConfidenceLevel())).count();
            sb.append("Empirical testing established **").append(findings.size())
                    .append("** findings, of which **").append(supported)
                    .append("** are supported by statistically significant evidence.\n\n");
        } else {
            sb.append("No empirical findings have been synthesized in this iteration.\n\n");
        }

        // Analysis coverage — distinguishes completed from unavailable analyses.
        sb.append("### Analysis coverage\n\n");
        sb.append("| Analysis | Status |\n| :--- | :--- |\n");
        sb.append("| Variable profiling | ").append(dataset.getColumns() == null || dataset.getColumns().isEmpty() ? "NOT RUN" : "COMPLETED").append(" |\n");
        sb.append("| Data quality audit | ").append(qualityReport != null ? "COMPLETED" : "NOT RUN").append(" |\n");
        sb.append("| EDA associations | ").append(associations != null && !associations.isEmpty() ? "COMPLETED (" + associations.size() + ")" : "NOT RUN").append(" |\n");
        sb.append("| Hypothesis tests | ").append(statisticalTests != null && !statisticalTests.isEmpty() ? "COMPLETED (" + statisticalTests.size() + ")" : "NOT RUN").append(" |\n");
        sb.append("| AutoML training | ").append(modelRuns != null && !modelRuns.isEmpty() ? "COMPLETED (" + modelRuns.size() + " models)" : "NOT RUN").append(" |\n");
        Map<String, Object> evaluation = bestRun == null ? Collections.emptyMap() : parseMap(bestRun.getEvaluationJson());
        boolean hasCalibration = evaluation.get("calibration") instanceof Map<?, ?>;
        boolean hasResiduals = evaluation.get("residualSummary") instanceof Map<?, ?>;
        sb.append("| Model diagnostics | ").append(hasCalibration ? "CALIBRATION" : hasResiduals ? "RESIDUALS" : "UNAVAILABLE").append(" |\n");
        sb.append("| Explainability (XAI) | ").append(bestRun != null && hasImportances(bestRun) ? "COMPLETED" : "UNAVAILABLE").append(" |\n");
        sb.append("| Fairness audit | ").append(bestRun != null && hasFairness(bestRun) ? "COMPLETED" : "NOT RUN").append(" |\n");
        sb.append("| Data drift | ").append(hasText(driftReportJson) ? "COMPLETED" : "NOT RUN").append(" |\n");
        sb.append("| Findings synthesis | ").append(findings != null && !findings.isEmpty() ? "COMPLETED (" + findings.size() + ")" : "NOT RUN").append(" |\n\n");

        // Dataset understanding
        sb.append("## 2. Dataset Understanding & Variable Profiling\n\n");
        sb.append("| Column Name | Inferred Type | Missing Count | Unique Values | Mean / Median | Std Dev | Range [Min, Max] | In Analysis |\n");
        sb.append("| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |\n");
        java.util.Set<String> excluded = ColumnSelection.excludedNames(dataset);
        for (DatasetColumn col : dataset.getColumns()) {
            String meanMed = col.getMeanVal() != null
                    ? String.format("%.2f / %.2f", col.getMeanVal(), col.getMedianVal())
                    : "N/A (Categorical)";
            String std = col.getStdDev() != null ? String.format("%.2f", col.getStdDev()) : "N/A";
            String range = col.getMinVal() != null
                    ? String.format("[%.2f, %.2f]", col.getMinVal(), col.getMaxVal())
                    : "N/A";
            String inAnalysis = excluded.contains(col.getColumnName()) ? "No (excluded)"
                    : ("IDENTIFIER".equals(col.getDataType()) ? "No (identifier)" : "Yes");
            sb.append(String.format("| `%s` | %s (%.0f%%) | %d (%.1f%%) | %d | %s | %s | %s | %s |\n",
                    col.getColumnName(), col.getDataType(), col.getTypeConfidence() * 100,
                    col.getMissingCount(), col.getMissingPct(), col.getUniqueCount(),
                    meanMed, std, range, inAnalysis));
        }
        int analyticCount = ColumnSelection.analytic(dataset).size();
        sb.append(String.format("\n**%d of %d variables enter analysis** (identifiers and user-excluded columns are "
                        + "listed above but never silently used in statistics, correlations, charts or models).\n\n",
                analyticCount, dataset.getColumnCount()));

        // Quality
        if (qualityReport != null) {
            sb.append("## 3. Data Quality & Hygiene Assessment\n\n");
            sb.append(String.format("- **Overall Quality Score**: `%.1f / 100`\n", qualityReport.getOverallScore()));
            sb.append(String.format("- **Missing Values Score**: `%.1f / 100`\n", qualityReport.getMissingValueScore()));
            sb.append(String.format("- **Duplicate Rows Score**: `%.1f / 100`\n", qualityReport.getDuplicateScore()));
            sb.append(String.format("- **Outlier Robustness Score**: `%.1f / 100`\n", qualityReport.getOutlierScore()));
            sb.append(String.format("- **Categorical Consistency**: `%.1f / 100`\n\n", qualityReport.getConsistencyScore()));
            if (qualityReport.getIssues() != null && !qualityReport.getIssues().isEmpty()) {
                sb.append("### Identified Quality Issues\n\n");
                sb.append("| Column | Issue Type | Severity | Description | Recommendation |\n");
                sb.append("| :--- | :--- | :--- | :--- | :--- |\n");
                for (DataQualityIssue issue : qualityReport.getIssues()) {
                    sb.append(String.format("| `%s` | %s | **%s** | %s | %s |\n",
                            issue.getColumnName() != null ? issue.getColumnName() : "Dataset-level",
                            issue.getIssueType(), issue.getSeverity(),
                            issue.getDescription(), issue.getRecommendation()));
                }
                sb.append("\n");
            }
        }

        // Associations
        if (associations != null && !associations.isEmpty()) {
            sb.append("## 4. Exploratory Associations & Bivariate Tests\n\n");
            sb.append("Statistical tests were performed with strictly aligned paired observations, zero-variance safeguards, and appropriate degrees of freedom.\n\n");
            sb.append("| Variable 1 | Variable 2 | Test Engine | Statistic | p-value | Effect Size | Significance | Interpretation |\n");
            sb.append("| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |\n");
            for (Association a : associations.stream().limit(20).toList()) {
                String sigText = Boolean.TRUE.equals(a.getIsSignificant()) ? "p < 0.05 (Sig)" : "Not Significant";
                sb.append(String.format("| `%s` | `%s` | %s | `%.3f` | `%.4e` | `%.3f` | %s | %s |\n",
                        a.getVar1(), a.getVar2(), a.getTestType(),
                        a.getStatistic(), a.getPValue(), a.getEffectSize(),
                        sigText, a.getInterpretation()));
            }
            sb.append("\n");
        }

        // Questions & hypotheses
        if (question != null || (hypotheses != null && !hypotheses.isEmpty())) {
            sb.append("## 5. Formulated Research Questions & Hypotheses\n\n");
            if (question != null) {
                sb.append("**Target Variable**: `").append(question.getTargetVariable()).append("`  \n");
                sb.append("**Predictor Variable**: `").append(question.getPredictorVariable()).append("`  \n");
                sb.append("**Suggested Statistical Engine**: `").append(question.getSuggestedTest()).append("`\n\n");
            }
            if (hypotheses != null) {
                for (int i = 0; i < hypotheses.size(); i++) {
                    Hypothesis h = hypotheses.get(i);
                    sb.append(String.format("### Hypothesis %d\n", i + 1));
                    sb.append("- **Null Hypothesis (H0)**: ").append(h.getNullHypothesis()).append("\n");
                    sb.append("- **Alternative Hypothesis (H1)**: ").append(h.getAltHypothesis()).append("\n");
                    sb.append("- **Scientific Rationale**: ").append(h.getRationale()).append("\n");
                    sb.append("- **Proposed Engine**: `").append(h.getSuggestedTest()).append("`\n\n");
                }
            }
        }

        // Statistical tests
        if (statisticalTests != null && !statisticalTests.isEmpty()) {
            sb.append("## 6. Empirical Hypothesis Testing Decisions\n\n");
            sb.append("| Hypothesis Pair | Test Type | Test Stat | p-value | Effect Size | Alpha | Decision | Interpretation |\n");
            sb.append("| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |\n");
            for (StatisticalTest t : statisticalTests) {
                String decision = Boolean.TRUE.equals(t.getIsStatisticallySignificant()) ? "**REJECT $H_0$**" : "FAIL TO REJECT $H_0$";
                sb.append(String.format("| `%s` vs `%s` | %s | `%.3f` | `%.4e` | `%.3f` (%s) | %.2f | %s | %s |\n",
                        t.getVar1(), t.getVar2() != null ? t.getVar2() : "-",
                        t.getTestType(), t.getStatistic(), t.getPValue(),
                        t.getEffectSize(), t.getEffectSizeType(), t.getAlpha(),
                        decision, t.getInterpretation()));
            }
            sb.append("\n");
        }

        // ML
        sb.append("## 7. Machine Learning & Model Performance\n\n");
        if (modelRuns != null && !modelRuns.isEmpty()) {
            sb.append("Models evaluated under leak-free 70/15/15 train/val/test splits with standard scaling and imputation fitted solely on training splits.\n\n");
            sb.append("| Model Name | Algorithm | Validation Metrics | Test Metrics | Status |\n");
            sb.append("| :--- | :--- | :--- | :--- | :--- |\n");
            for (ModelRun run : modelRuns) {
                String bestTag = Boolean.TRUE.equals(run.getIsBestModel()) ? "[BEST MODEL]" : "Candidate";
                sb.append(String.format("| %s | `%s` | %s | %s | %s |\n",
                        run.getModelName(), run.getAlgorithm(),
                        formatMetrics(run.getValMetricsJson()),
                        formatMetrics(run.getTestMetricsJson()),
                        bestTag));
            }
            sb.append("\n");
        } else {
            sb.append("*Machine Learning: Not performed.*\n\n");
        }

        // Model diagnostics: calibration for classifiers, residual summary for regressors.
        if (bestRun != null && evaluation.get("calibration") instanceof Map<?, ?> calibration) {
            sb.append("### Model calibration (reliability)\n\n");
            sb.append(String.format("Reliability diagram from the held-out test partition for `%s`; "
                    + "Brier score **%.4f** (lower is better).\n\n", bestRun.getModelName(),
                    asDouble(calibration.get("brierScore"))));
            sb.append("| Mean predicted probability | Observed frequency | N |\n");
            sb.append("| :--- | :--- | :--- |\n");
            Object bins = calibration.get("bins");
            if (bins instanceof List<?> list) {
                for (Object o : list) {
                    if (o instanceof Map<?, ?> m) {
                        sb.append(String.format("| %.4f | %.4f | %s |\n",
                                asDouble(m.get("meanPredicted")), asDouble(m.get("observedFrequency")),
                                m.get("count") == null ? "–" : m.get("count")));
                    }
                }
            }
            sb.append("\n");
        } else if (bestRun != null && evaluation.get("residualSummary") instanceof Map<?, ?> residuals) {
            sb.append("### Residual diagnostics\n\n");
            sb.append("| Mean error | Mean absolute error | Max absolute error |\n");
            sb.append("| :--- | :--- | :--- |\n");
            sb.append(String.format("| %.4f | %.4f | %.4f |\n\n",
                    asDouble(residuals.get("meanError")), asDouble(residuals.get("meanAbsoluteError")),
                    asDouble(residuals.get("maxAbsoluteError"))));
        } else if (bestRun != null) {
            sb.append("*Model diagnostics: not available for this run (evaluation artifacts were not persisted).*\n\n");
        }

        // XAI
        sb.append("## 8. Explainability (XAI)\n\n");
        List<Map<String, Object>> importances = bestRun == null ? Collections.emptyList()
                : parseList(bestRun.getFeatureImportancesJson());
        if (!importances.isEmpty()) {
            sb.append(String.format("Global feature importance for `%s` evaluated using empirical permutation importance "
                            + "on the held-out partition (no target leakage).\n\n", bestRun.getModelName()));
            sb.append("| Rank | Feature | Importance | Relative % | Direction |\n");
            sb.append("| :--- | :--- | :--- | :--- | :--- |\n");
            int rank = 1;
            for (Map<String, Object> imp : importances) {
                sb.append(String.format("| %d | `%s` | %.4f | %.1f%% | %s |\n", rank++,
                        imp.getOrDefault("featureName", "?"),
                        asDouble(imp.get("importanceScore")),
                        asDouble(imp.get("relativePercentage")),
                        imp.getOrDefault("direction", "NON_LINEAR")));
            }
            sb.append("\n");
        } else {
            sb.append("*Explainability: Not available because no trained model with feature importances exists. "
                    + "Re-run AutoML training to produce explanations.*\n\n");
        }

        // Fairness
        sb.append("## 9. Algorithmic Fairness & Bias Audit\n\n");
        Map<String, Object> fairness = bestRun == null ? Collections.emptyMap()
                : parseMap(bestRun.getFairnessMetricsJson());
        if (!fairness.isEmpty() && fairness.get("disparateImpactStatus") != null) {
            String status = String.valueOf(fairness.get("disparateImpactStatus"));
            sb.append(String.format("- **Sensitive variable**: `%s`\n", fairness.getOrDefault("sensitiveColumn", "–")));
            sb.append(String.format("- **Demographic parity ratio**: `%.3f`\n", asDouble(fairness.get("demographicParityRatio"))));
            sb.append(String.format("- **EEOC four-fifths status**: **%s**\n", status));
            Object rates = fairness.get("groupPositiveRates");
            if (rates instanceof Map<?, ?> map && !map.isEmpty()) {
                sb.append("\n| Group | Positive rate |\n| :--- | :--- |\n");
                map.forEach((k, v) -> sb.append(String.format("| `%s` | %.3f |\n", k, asDouble(v))));
            }
            if (fairness.get("recommendation") != null) {
                sb.append("\n**Recommendation**: ").append(fairness.get("recommendation")).append("\n");
            }
            sb.append("\n");
        } else {
            sb.append("*Fairness audit: not run for this model. Run AutoML with a sensitive/grouping column "
                    + "selected to produce real fairness metrics.*\n\n");
        }

        // Drift
        sb.append("## 10. Data Drift & Distributional Stability\n\n");
        Map<String, Object> drift = parseMap(driftReportJson);
        if (!drift.isEmpty()) {
            sb.append(String.format("Comparison against reference dataset `%s`.\n\n", drift.getOrDefault("referenceDatasetName", "–")));
            sb.append(String.format("- **Overall status**: **%s**\n", drift.getOrDefault("overallStatus", "–")));
            sb.append(String.format("- **Average PSI**: `%.4f`\n", asDouble(drift.get("overallDriftIndex"))));
            sb.append(String.format("- **Drifted features**: `%s` of `%s`\n\n",
                    drift.getOrDefault("driftedFeaturesCount", "–"), drift.getOrDefault("totalFeaturesAnalyzed", "–")));
            Object cols = drift.get("columnDrifts");
            if (cols instanceof List<?> list && !list.isEmpty()) {
                sb.append("| Variable | Type | PSI | Status | p-value | Interpretation |\n");
                sb.append("| :--- | :--- | :--- | :--- | :--- | :--- |\n");
                for (Object o : list) {
                    if (o instanceof Map<?, ?> m) {
                        sb.append(String.format("| `%s` | %s | %.4f | %s | %.4f | %s |\n",
                                m.get("columnName"), m.get("dataType"), asDouble(m.get("psiScore")),
                                m.get("driftStatus"), asDouble(m.get("pValue")), m.get("interpretation")));
                    }
                }
                sb.append("\n");
            }
            if (drift.get("summaryRecommendation") != null) {
                sb.append("**Recommendation**: ").append(drift.get("summaryRecommendation")).append("\n\n");
            }
        } else {
            sb.append("*Data drift: not run. Run the drift comparison from the dataset page to produce drift "
                    + "evidence (PSI, KS and significance tests) for this report.*\n\n");
        }

        // Findings
        sb.append("## 11. Synthesized Scientific Findings & Evidence Graph\n\n");
        if (findings != null && !findings.isEmpty()) {
            for (Finding f : findings) {
                sb.append("### ").append(f.getTitle()).append("\n");
                sb.append("**Confidence Level**: `").append(f.getConfidenceLevel()).append("`  \n\n");
                sb.append(f.getSummary()).append("\n\n");
                sb.append("**Empirical Evidence Node**:\n").append(f.getEvidenceText()).append("\n\n");
            }
        } else {
            sb.append("No empirical findings synthesized for this dataset yet.\n\n");
        }

        // Limitations
        sb.append("## 12. Methodological Limitations & Strict Causality Disclaimer\n\n");
        sb.append("> **CAUTION & SCIENTIFIC INTEGRITY NOTICE**  \n");
        sb.append("> 1. **Correlation vs. Causation**: Statistical significance (p < 0.05) and high correlation establish mathematical association, not causal influence. Unmeasured confounding, selection bias, and reverse causality cannot be ruled out without randomized controlled trials or a formal causal model.  \n");
        sb.append("> 2. **Observational Data Constraints**: Findings generated by this platform are observational and descriptive.  \n");
        sb.append("> 3. **Multiple Hypothesis Testing**: When exploring large feature spaces, family-wise error rates or false discovery rates (FDR) may increase unless explicit correction (e.g. Benjamini-Hochberg) is enforced.  \n");
        sb.append("> 4. **Generalizability**: Generalization to external populations requires verification against out-of-distribution drift and external cohort validation.\n\n");

        // Reproducibility
        sb.append("## 13. Conclusion & Reproducibility\n\n");
        sb.append("| Reproducibility Item | Value |\n| :--- | :--- |\n");
        sb.append(String.format("| Dataset version | v%d |\n", dataset.getVersion() == null ? 1 : dataset.getVersion()));
        sb.append(String.format("| Source format | %s |\n", dataset.getSourceFormat() == null ? "CSV" : dataset.getSourceFormat()));
        if (dataset.getSheetName() != null) sb.append(String.format("| Worksheet | %s |\n", dataset.getSheetName()));
        sb.append(String.format("| Rows × columns | %d × %d |\n", dataset.getRowCount(), dataset.getColumnCount()));
        sb.append(String.format("| Analytic variables | %d |\n", analyticCount));
        if (bestRun != null) {
            sb.append(String.format("| Best model | %s (%s) |\n", bestRun.getModelName(), bestRun.getAlgorithm()));
            sb.append(String.format("| Random seed | %s |\n", bestRun.getRandomSeed() == null ? "–" : bestRun.getRandomSeed()));
            sb.append(String.format("| Train / validation / test rows | %s / %s / %s |\n",
                    bestRun.getTrainRows(), bestRun.getValRows(), bestRun.getTestRows()));
        }
        if (bestRun != null && bestRun.getExperimentVersion() != null
                && bestRun.getExperimentVersion().getEngineVersion() != null) {
            sb.append(String.format("| Engine version | %s |\n", bestRun.getExperimentVersion().getEngineVersion()));
        }
        sb.append("\nAll computations use deterministic pure-Java implementations (Apache Commons Math and the "
                + "AutoScientist AI core engines). Every claim above is traceable to stored observations and persisted "
                + "analysis runs.\n\n");
        sb.append("---\n*End of Report — AutoScientist AI Research Provenance Graph verified.*");

        return sb.toString();
    }

    private boolean hasImportances(ModelRun run) {
        return run.getFeatureImportancesJson() != null && !run.getFeatureImportancesJson().isBlank()
                && !"[]".equals(run.getFeatureImportancesJson().trim());
    }

    private boolean hasFairness(ModelRun run) {
        return run.getFairnessMetricsJson() != null && !run.getFairnessMetricsJson().isBlank();
    }

    private boolean hasText(String s) {
        return s != null && !s.isBlank();
    }

    private List<Map<String, Object>> parseList(String json) {
        if (!hasText(json)) return Collections.emptyList();
        try {
            return objectMapper.readValue(json, new TypeReference<List<Map<String, Object>>>() {});
        } catch (Exception e) {
            return Collections.emptyList();
        }
    }

    private Map<String, Object> parseMap(String json) {
        if (!hasText(json)) return Collections.emptyMap();
        try {
            return objectMapper.readValue(json, new TypeReference<Map<String, Object>>() {});
        } catch (Exception e) {
            return Collections.emptyMap();
        }
    }

    private double asDouble(Object v) {
        if (v instanceof Number n) return n.doubleValue();
        try { return v == null ? 0.0 : Double.parseDouble(String.valueOf(v)); }
        catch (Exception e) { return 0.0; }
    }

    /**
     * Render a persisted metric map as a compact, human-readable cell rather than a raw
     * JSON blob. Standard classification/regression metrics are shown with fixed precision;
     * any unrecognised numeric key is still surfaced as {@code key=value}.
     */
    private String formatMetrics(String json) {
        Map<String, Object> metrics = parseMap(json);
        if (metrics.isEmpty()) return "N/A";
        List<String> parts = new ArrayList<>();
        appendMetric(parts, metrics, "accuracy", "acc", 4);
        appendMetric(parts, metrics, "precision", "prec", 4);
        appendMetric(parts, metrics, "recall", "rec", 4);
        appendMetric(parts, metrics, "f1", "f1", 4);
        appendMetric(parts, metrics, "f1Score", "f1", 4);
        appendMetric(parts, metrics, "r2", "R2", 4);
        appendMetric(parts, metrics, "r2Score", "R2", 4);
        appendMetric(parts, metrics, "rmse", "RMSE", 4);
        appendMetric(parts, metrics, "mae", "MAE", 4);
        appendMetric(parts, metrics, "mse", "MSE", 4);
        // Fall back to any remaining numeric metrics not already shown.
        Set<String> handled = Set.of("accuracy", "precision", "recall", "f1", "f1Score",
                "r2", "r2Score", "rmse", "mae", "mse",
                "true_positives", "false_positives", "false_negatives", "true_negatives",
                "tp", "fp", "tn", "fn");
        metrics.forEach((k, v) -> {
            if (handled.contains(k)) return;
            if (v instanceof Number n) {
                parts.add(String.format("%s=%.4f", k, n.doubleValue()));
            }
        });
        if (parts.isEmpty()) return "N/A";
        return String.join(", ", parts);
    }

    private void appendMetric(List<String> parts, Map<String, Object> metrics, String key, String label, int precision) {
        Object v = metrics.get(key);
        if (v instanceof Number n) {
            parts.add(String.format("%s=%.4f", label, n.doubleValue()));
        }
    }
}
